def cycle_year(y: int) -> int:
    """0 大选年 / 1 大选后一年 / 2 中期选举年 / 3 大选前一年（1972 是大选年）。"""
    return (y - 1972) % 4


def election_day(y: int) -> D:
    """美国联邦选举日：11 月第一个周一之后的那个周二（落在 11 月 2–8 日）。"""
    d = D(y, 11, 2)
    while d.weekday() != 1:
        d += DAY
    return d


def cycle_start(y: int) -> int:
    """当前四年周期的起点（中期选举年）。看板四列 = 起点起的四年。"""
    return y - ((cycle_year(y) - 2) % 4)


