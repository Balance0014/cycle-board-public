def fmt_pct(x: float) -> str:
    return f"{x * 100:+.0f}%"


def fmt_ym(d: D) -> str:
    return f"{d.year % 100}年{d.month}月"


def fmt_ymd(d: D) -> str:
    return f"{d.year % 100}年{d.month}月{d.day}日"


def fmt_ym_range(a: D, b: D) -> str:
    if (a.year, a.month) == (b.year, b.month):
        return fmt_ym(a)
    if a.year == b.year:
        return f"{a.year % 100}年{a.month}–{b.month}月"
    return f"{fmt_ym(a)}–{fmt_ym(b)}"


