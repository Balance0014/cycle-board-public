def direction_label(up: int, n: int) -> str:
    if n == 0:
        return "无数据"
    r = up / n
    if r >= STRONG:
        return "涨"
    if r <= 1 - STRONG:
        return "跌"
    if r >= LEAN:
        return "偏涨"
    if r <= 1 - LEAN:
        return "偏跌"
    return "不稳"


