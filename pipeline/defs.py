def verdict(k: int, n: int, base: float, floor: float = STRONG) -> bool:
    """「比平时强」这一关：本身比例 ≥ floor，且比平时高 EDGE 以上。"""
    return n > 0 and k / n >= floor and k / n - base >= EDGE - 1e-9


def verdict_word(k: int, n: int, base: float, robust: bool) -> str:
    """表格里「有没有用」那一格，全看板同一把尺子（定义见下面 words()）：
    有用 = verdict 过关，换几种合理算法也都过关；
    有点用 = 和平时差 EDGE 以上，但不够硬（成立的不到 STRONG，或换一种算法就不过）；
    跟平时一样 = 和平时差不到 EDGE。"""
    if verdict(k, n, base) and robust:
        return VERDICT_WORDS[0]
    if n > 0 and abs(k / n - base) >= EDGE - 1e-9:
        return VERDICT_WORDS[1]
    return VERDICT_WORDS[2]


